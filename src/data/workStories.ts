/** すべての名曲の物語 */
export const WORK_STORIES: Record<string, WrittenChapter[]> = mergeParts(WORK_STORY_PARTS);

/** その曲の物語（なければ null） */
export function getWorkStory(work: Composition, composer: Composer): Story | null {
  const list = WORK_STORIES[work.id];
  if (!list) return null;
  void composer;
  const chapters: StoryChapter[] = list
    .map((c, i) => {
      const place = PLACES[c.place];
      if (!place) return null;
      return {
        year: c.year,
        end: c.end ?? c.year,
        place,
        title: c.title,
        text: c.text,
        image: c.image,
        caption: c.caption,
        illustration: illustrationFor(work.id, i),
        aside: c.aside,
        works: []
      } as StoryChapter;
    })
    .filter((c): c is StoryChapter => !!c);
  return { chapters, written: true };
}

export const hasWorkStory = (workId: string) => !!WORK_STORIES[workId];
