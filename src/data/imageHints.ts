/** 文章の中に手がかりのキーワードがあれば、その写真の鍵（'英語名|日本語名'）を返す */
export function imageKeyFor(text: string): string {
  const hit = HINTS.find(([word]) => (word.startsWith('=') ? text === word.slice(1) : text.includes(word)));
  return hit ? hit[1] : '';
}
