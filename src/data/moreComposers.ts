import { Composer, Composition, EraId, InstrumentType, NoteEvent } from '../types';
import { PLACES } from './places';
import { ITINERARY_RAW_MORE } from './itineraryDataMore';

/**
 * 追加した作曲家のデータ。1人ぶんを「種」(ComposerSeed) として短く書き、
 * Composer の完全な形に組み立てる。滞在地(cities)は itineraryDataMore.ts から自動で作る。
 * 肖像画は用意できていないため、画像なし（シルエット表示）にしている。
 */
type WorkSeed = [
  id: string,
  title: string,
  originalTitle: string,
  year: number,
  genre: Composition['genre'],
  genreJa: string,
  place: string,
  description: string,
  notes?: string,
  instrument?: InstrumentType,
  tempo?: number
];

interface ComposerSeed {
  id: string;
  category?: 'japan-trad' | 'world';
  name: string;
  en: string;
  short: string;
  birth: number;
  death: number;
  era: EraId;
  country: string;
  flag: string;
  bio: string;
  style: string;
  features: string[];
  peers: string[];
  birthPlace: string;
  deathPlace: string;
  birthEp: string;
  deathEp: string;
  milestones: [number, string][];
  works: WorkSeed[];
}

/** "F#5:2 E5:2 R:1" のような短い書き方を NoteEvent の並びにする（空なら試聴なし） */
const parseNotes = (text?: string): NoteEvent[] =>
  (text || '')
    .split(/\s+/)
    .filter(Boolean)
    .map(token => {
      const [note, duration] = token.split(':');
      return { note, duration: parseFloat(duration) };
    });

const build = (s: ComposerSeed): Composer => {
  const stays = ITINERARY_RAW_MORE[s.id] || [];
  return {
    id: s.id,
    category: s.category,
    name: s.name,
    originalName: s.en,
    shortName: s.short,
    birthYear: s.birth,
    deathYear: s.death,
    era: s.era,
    country: s.country,
    nationalityJa: s.country,
    flag: s.flag,
    portraitUrl: '',
    biography: s.bio,
    musicalStyle: s.style,
    keyFeatures: s.features,
    contemporaries: s.peers,
    cities: stays.map(([start, end, key, note]) => {
      const p = PLACES[key];
      return {
        cityName: key,
        cityNameJa: p?.ja || key,
        country: p?.country || s.country,
        coordinates: [p?.lon ?? 0, p?.lat ?? 0] as [number, number],
        startYear: start,
        endYear: end,
        role: note,
        notableEvent: note
      };
    }),
    works: s.works.map(([id, title, originalTitle, year, genre, genreJa, place, description, notes, instrument, tempo]) => {
      const p = PLACES[place];
      return {
        id,
        title,
        originalTitle,
        year,
        genre,
        genreJa,
        city: p?.ja || place,
        cityCoordinates: [p?.lon ?? 0, p?.lat ?? 0] as [number, number],
        description,
        audioSnippet: {
          type: 'synth' as const,
          instrument: instrument || 'piano',
          tempo: tempo || 90,
          notes: parseNotes(notes)
        }
      };
    }),
    milestones: s.milestones.map(([year, event]) => ({ year, event })),
    birthPlace: s.birthPlace,
    deathPlace: s.deathPlace,
    birthEpisode: s.birthEp,
    deathEpisode: s.deathEp
  };
};

