export function getWorkGuide(composerId: string, work: Composition): { text: string; specific: boolean } {
  const g = GUIDES.find(x => x.composer === composerId && (x.match === '' || work.title.includes(x.match)));
  if (g) return { text: g.text, specific: true };
  return { text: BY_GENRE[work.genre] ?? '', specific: false };
}
